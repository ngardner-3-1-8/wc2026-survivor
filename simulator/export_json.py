def write_json(data, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path,"w") as f:
        json.dump(data, f, indent=2)
    print(f"  ✓ {path}  ({path.stat().st_size//1024}KB)")

